"""Per-category breakdown and paired bootstrap CIs (system − baseline) from results/*.json rows.

python -m lexbridge.eval.significance --system lexbridge --baseline bm25
→ results/<profile>/significance.json and paper/tables/<profile>/significance.tex
"""
from __future__ import annotations

import argparse
import json
import random

from ..config import get_config

METRICS = [("prec", "P@5"), ("mrr", "MRR"), ("ndcg", "nDCG@5"), ("cer", "CER@5"), ("code_correct", "Code acc"),
           ("temporal_correct", "Temporal acc")]


def paired_bootstrap(a: list[float], b: list[float], iters: int = 5000, seed: int = 0):
    rnd = random.Random(seed)
    n = len(a)
    diffs = []
    for _ in range(iters):
        idx = [rnd.randrange(n) for _ in range(n)]
        diffs.append(sum(a[i] - b[i] for i in idx) / n)
    diffs.sort()
    mean = sum(x - y for x, y in zip(a, b)) / n
    p = sum(d <= 0 for d in diffs) / iters if mean > 0 else sum(d >= 0 for d in diffs) / iters
    return mean, diffs[int(0.025 * iters)], diffs[int(0.975 * iters)], p


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--system", default="lexbridge")
    ap.add_argument("--baseline", default="bm25")
    ap.add_argument("--tag", default="")
    a = ap.parse_args(argv)
    cfg = get_config()
    R = cfg.path("results")
    sys_rows = {r["qid"]: r for r in json.loads((R / f"{a.system}{a.tag}.json").read_text())["rows"]}
    base_rows = {r["qid"]: r for r in json.loads((R / f"{a.baseline}{a.tag}.json").read_text())["rows"]}
    cats = sorted({r["category"] for r in sys_rows.values()})
    out = {"system": a.system, "baseline": a.baseline, "overall": {}, "per_category": {}}
    for key, name in METRICS:
        q = [k for k in sys_rows if sys_rows[k].get(key) is not None and base_rows.get(k, {}).get(key) is not None]
        if not q:
            continue
        x, y = [float(sys_rows[k][key]) for k in q], [float(base_rows[k][key]) for k in q]
        m, lo, hi, p = paired_bootstrap(x, y)
        out["overall"][name] = {"n": len(q), "system": round(sum(x) / len(x), 4), "baseline": round(sum(y) / len(y), 4),
                                "diff": round(m, 4), "ci95": [round(lo, 4), round(hi, 4)], "p": round(p, 4)}
        for c in cats:
            qc = [k for k in q if sys_rows[k]["category"] == c]
            if qc:
                out["per_category"].setdefault(c, {})[name] = {
                    "n": len(qc), "system": round(sum(float(sys_rows[k][key]) for k in qc) / len(qc), 4),
                    "baseline": round(sum(float(base_rows[k][key]) for k in qc) / len(qc), 4)}
    (R / f"significance_{a.system}_vs_{a.baseline}{a.tag}.json").write_text(json.dumps(out, indent=2))
    T = cfg.path("tables")
    T.mkdir(parents=True, exist_ok=True)
    lines = ["% AUTO-GENERATED by lexbridge.eval.significance (paired bootstrap, 5000 resamples)",
             "\\begin{table}[t]", "\\centering\\small", "\\begin{tabular}{lcccc}", "\\toprule",
             f"Metric & {a.system} & {a.baseline} & $\\Delta$ [95\\% CI] & $p$ \\\\", "\\midrule"]
    for name, v in out["overall"].items():
        lines.append(f"{name} & {v['system']:.3f} & {v['baseline']:.3f} & {v['diff']:+.3f} [{v['ci95'][0]:+.3f}, {v['ci95'][1]:+.3f}] & {v['p']:.3f} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", f"\\caption{{{a.system} vs.\\ {a.baseline}: paired bootstrap.}}",
              "\\label{tab:sig}", "\\end{table}", ""]
    (T / f"significance_{a.baseline}{a.tag}.tex").write_text("\n".join(lines))
    print(json.dumps(out, indent=2))


if __name__ == "__main__":
    main()
