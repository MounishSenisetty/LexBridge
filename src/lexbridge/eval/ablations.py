"""Ablations + LaTeX tables: paper/tables/main.tex and paper/tables/ablation.tex.

python -m lexbridge.eval.ablations
"""
from __future__ import annotations

from ..config import get_config
from ..generate.pipeline import ABLATIONS
from ..resources import load_resources
from .run_eval import SYSTEMS, fmt, load_questions, run

MAIN_COLS = [("CER@5", "CER@5$\\downarrow$"), ("code_resolution_acc", "Code acc"), ("Recall@5", "R@5"),
             ("MRR", "MRR"), ("nDCG@5", "nDCG@5"), ("transfer_macroF1", "Transfer F1"),
             ("temporal_acc", "Temporal acc"), ("citation_P", "Cit.~P"), ("citation_R", "Cit.~R"),
             ("faithfulness", "Faith.")]
PRETTY = {"no_rag": "No-RAG", "bm25": "BM25-RAG", "dense": "Dense-RAG", "hybrid": "Hybrid-RAG",
          "lexbridge": "\\textbf{LexBridge}"}
NOTE = ("% AUTO-GENERATED by lexbridge.eval.ablations. Fixture corpus + deterministic mock LLM:\n"
        "% these numbers check that the pipeline runs; they are NOT research results.\n")


def latex_table(results: dict, caption: str, label: str, names=None, pretty=None) -> str:
    names = names or list(results)
    pretty = pretty or {}
    head = " & ".join(h for _, h in MAIN_COLS)
    lines = [NOTE, "\\begin{table*}[t]", "\\centering\\small", f"\\begin{{tabular}}{{l{'c' * len(MAIN_COLS)}}}",
             "\\toprule", f"System & {head} \\\\", "\\midrule"]
    for n in names:
        s = results[n]["summary"]
        lines.append(f"{pretty.get(n, n.replace('-', '$-$'))} & " + " & ".join(fmt(s.get(k)) for k, _ in MAIN_COLS) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", f"\\caption{{{caption}}}", f"\\label{{{label}}}", "\\end{table*}", ""]
    return "\n".join(lines)


def main():
    res = load_resources()
    qs = load_questions()
    tables = get_config().path("tables")
    tables.mkdir(parents=True, exist_ok=True)
    main_res = run(SYSTEMS, qs, res)
    n = len(qs)
    (tables / "main.tex").write_text(latex_table(
        main_res, f"Main results on the LexBridge-QA draft sample ($n={n}$, fixture corpus, mock LLM; not research results).",
        "tab:main", SYSTEMS, PRETTY))
    abl = run(list(ABLATIONS), qs, res, write=False)
    (tables / "ablation.tex").write_text(latex_table(
        abl, f"Ablations of LexBridge components ($n={n}$, fixture corpus, mock LLM).", "tab:ablation"))
    for name, r in {**main_res, **abl}.items():
        print(f"{name:<24}", " ".join(f"{k}={fmt(r['summary'].get(k))}" for k, _ in MAIN_COLS))
    print(f"wrote {tables/'main.tex'} and {tables/'ablation.tex'}")


if __name__ == "__main__":
    main()
